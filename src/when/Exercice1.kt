package `when`

fun main() {

    var n: Int = 4
    when (n) {
        1 -> println("Lundi")
        2 -> println("Mardi")
        3 -> println("Mercredi")
        4 -> println("Jeudi")
        5 -> println("Vendredi")
        6 -> println("Week-end")
        7 -> println("Week-end")
        else -> println("Jour invalide")
    }

}